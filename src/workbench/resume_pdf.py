def _section_html(section) -> str:
    title = _field(section.get("title", ""), "section-title")
    chunks = ['<div class="section-heading"><span class="heading-text">%s</span><i class="heading-line"></i></div>' % title]
    for item in section.get("items", []):
        section_type = section.get("type")
        if section_type == "skills":
            chunks.append('<div class="skill-item"><div class="skill-text">%s</div></div>' % _inline(item.get("content", "")))
            continue
        if section_type == "experience":
            fields = (item.get("organization", ""), item.get("role", ""), item.get("date", ""))
        elif section_type == "projects":
            fields = (item.get("title", ""), item.get("responsibility", ""), item.get("date", ""))
        else:
            fields = (item.get("school", ""), item.get("major", ""), item.get("date", ""))
        header_class = "%s-header" % ("experience" if section_type == "experience" else "project" if section_type == "projects" else "education")
        chunks.append('<article class="entry-block"><div class="entry"><div class="entry-header %s">%s</div>' % (header_class, _join_fields(fields)))
        bullets = item.get("bullets", [])
        for bullet in bullets:
            chunks.append('<div class="resume-bullet"><div class="bullet-text">%s</div></div>' % _inline(bullet.get("content", "")))
        chunks.append("</div></article>")
    return "".join(chunks)


def _contact_html(contact) -> str:
    value = _contact_value(contact)
    if not value:
        return ""
    href = str(contact.get("href", ""))
    contact_type = _contact_type(contact)
    if contact_type == "github":
        icon = _contact_icon(contact)
        return '<span class="contact-item contact-item-github">%s</span>' % (
            '<a class="contact-github-link" href="%s">%s</a>' % (html.escape(href, quote=True), icon)
            if href.startswith(("https://", "http://")) else icon
        )
    value_html = html.escape(value, quote=False)
    link = ''
    if contact.get("kind") == "link":
        link = ' <a class="contact-link-open%s" href="%s">↗</a>' % (
            "" if href.startswith(("https://", "http://")) else " disabled",
            html.escape(href, quote=True) if href.startswith(("https://", "http://")) else "#",
        )
        return '<span class="contact-item">%s%s</span>' % (value_html, link)
    return '<span class="contact-item"><span class="contact-icon-wrap">%s</span><span class="contact-text">%s</span></span>' % (_contact_icon(contact), value_html)


def _font_face() -> str:
    global _FONT_DATA
    if _FONT_DATA is None:
        if _FONT_PATH.is_file():
            encoded = base64.b64encode(_FONT_PATH.read_bytes()).decode("ascii")
            _FONT_DATA = "@font-face{font-family:CareerResumeCN;src:url(data:font/woff2;base64,%s) format('woff2');font-style:normal;font-weight:200 900;}" % encoded
        else:
            _FONT_DATA = ""
    return _FONT_DATA


