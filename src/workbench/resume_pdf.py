def _chrome_executable() -> Optional[str]:
    configured = os.environ.get("CAREER_CHROME_EXECUTABLE")
    candidates = [configured] if configured else []
    candidates += [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        shutil.which("chromium"),
        shutil.which("google-chrome"),
    ]
    return next((path for path in candidates if path and Path(path).is_file()), None)


def render_pdf(document) -> RenderedResumePDF:
    """Render one validated document into a real, selectable text PDF."""
    validated = validate_document(document)
    executable = _chrome_executable()
    if not executable:
        raise ResumePDFError("未找到本地 Chromium/Chrome，未生成 PDF；请按部署依赖安装固定浏览器")
    from .core import digest

    data = None
    renderer_version = None
    playwright = None
    browser = None
    context = None
    try:
        from playwright.sync_api import Error as PlaywrightError, sync_playwright
    except ImportError as exc:
        raise ResumePDFError("未安装 Playwright，未生成 PDF；请按锁定依赖安装渲染器") from exc
    try:
        playwright = sync_playwright().start()
        browser = playwright.chromium.launch(headless=True, executable_path=executable, timeout=30000)
        renderer_version = "playwright-1.51.0-chrome-%s" % browser.version
        context = browser.new_context(java_script_enabled=False, service_workers="block", locale="zh-CN")
        page = context.new_page()
        page.route("**/*", lambda route: route.abort())
        page.set_content(_html_document(validated), wait_until="load", timeout=30000)
        page.wait_for_timeout(100)
        data = page.pdf(format="A4", print_background=True, prefer_css_page_size=True)
    except (PlaywrightError, OSError) as exc:
        raise ResumePDFError("本地 Chromium PDF 渲染失败：%s" % exc) from exc
    finally:
        if context is not None:
            context.close()
        if browser is not None:
            browser.close()
        if playwright is not None:
            playwright.stop()
    if not data or not data.startswith(b"%PDF-") or b"%%EOF" not in data[-1024:]:
        raise ResumePDFError("本地 Chromium 未返回有效 PDF")
    return RenderedResumePDF(data=data, renderer_version=renderer_version, document_hash=digest(validated))
