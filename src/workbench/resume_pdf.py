"""Controlled, text-first PDF rendering for structured resume documents.

The renderer receives only the validated structured document.  It creates an
isolated Playwright context containing static HTML generated by this module;
there is no user browser profile, JavaScript, external URL, or file URL in the
rendering path.  The PDF is produced by Chromium's print engine, so the output
keeps a real text layer and can flow across A4 pages.
"""
from dataclasses import dataclass
import base64
import html
import os
from html.parser import HTMLParser
from pathlib import Path
import re
import shutil
from typing import Optional

from .editor import validate_document


class ResumePDFError(RuntimeError):
    """A local renderer or controlled template failure."""


@dataclass(frozen=True)
class RenderedResumePDF:
    data: bytes
    renderer_version: str
    document_hash: str


_FONT_DATA: Optional[str] = None
_FONT_PATH = Path(__file__).resolve().parents[2] / "frontend" / "public" / "assets" / "fonts" / "SourceHanSansCN-VF.woff2"
_ALLOWED_TAGS = {"b", "strong", "i", "em", "u", "br", "font", "span"}
_FONT_SIZE = re.compile(r"^\d+(?:\.5)?pt$")


class _InlineHTML(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []

    def handle_data(self, data):
        self.parts.append(html.escape(data, quote=False))

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()
        if tag not in _ALLOWED_TAGS:
            return
        attributes = dict(attrs)
        if tag == "br":
            self.parts.append("<br>")
        elif tag == "font" and re.fullmatch(r"[1-7]", attributes.get("size", "")):
            self.parts.append('<span class="font-size-%s">' % attributes["size"])
        elif tag == "span" and _FONT_SIZE.fullmatch(attributes.get("style", "").replace("font-size:", "").strip()):
            size = attributes["style"].replace("font-size:", "").strip()
            self.parts.append('<span style="font-size:%s">' % html.escape(size, quote=True))
        elif tag in {"b", "strong", "i", "em", "u", "span"}:
            self.parts.append("<%s>" % tag)

    def handle_endtag(self, tag):
        tag = tag.lower()
        if tag in {"b", "strong", "i", "em", "u", "span", "font"}:
            self.parts.append("</span>" if tag == "font" else "</%s>" % tag)


def _inline(value) -> str:
    parser = _InlineHTML()
    parser.feed(str(value or ""))
    parser.close()
    return "".join(parser.parts)


def _plain(value) -> str:
    parser = _InlineHTML()
    parser.feed(str(value or ""))
    parser.close()
    return re.sub(r"\s+", " ", "".join(parser.parts).replace("<br>", " ")).strip()


def _field(value, class_name="field") -> str:
    content = _inline(value)
    if not _plain(value):
        return ""
    return '<span class="%s">%s</span>' % (class_name, content)


def _join_fields(values) -> str:
    fields = []
    for index, value in enumerate(values):
        content = _inline(value)
        classes = "field entry-date" if index == len(values) - 1 else "field"
        fields.append('<span class="%s">%s</span>' % (classes, content))
    return "".join(fields)


def _contact_type(contact) -> str:
    text = _plain(contact.get("content", "")).strip()
    kind = contact.get("kind")
    if kind == "link":
        if re.search(r"^github\s*[：:]", text, re.I) or re.search(r"(?:^|/)github\.com(?:/|$)", str(contact.get("href", "")), re.I):
            return "github"
        return "link"
    stable = {"contact-phone": "phone", "contact-email": "email", "contact-wechat": "wechat"}.get(str(contact.get("id", "")))
    if stable:
        return stable
    if re.search(r"^(微信|wechat)\s*[：:]", text, re.I):
        return "wechat"
    if re.search(r"^(邮箱|email)\s*[：:]", text, re.I) or re.search(r"[^\s@]+@[^\s@]+\.[^\s@]+", text):
        return "email"
    if re.search(r"^(电话|手机|phone)\s*[：:]", text, re.I) or re.fullmatch(r"[+\d ()-]{7,}", re.sub(r"^联系方式\s*[：:]?\s*", "", text)):
        return "phone"
    return "identity"


def _contact_value(contact) -> str:
    text = _plain(contact.get("content", ""))
    if contact.get("kind") == "link":
        return re.sub(r"^GitHub\s*[：:]\s*", "", text, flags=re.I) if _contact_type(contact) == "github" else text
    return re.sub(r"^(电话|手机|邮箱|微信|联系方式|phone|email|wechat)\s*[：:]?\s*", "", text, flags=re.I)


